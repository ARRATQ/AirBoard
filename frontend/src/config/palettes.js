export function getPalette(slug) {
  return PALETTES.find(p => p.slug === slug) || PALETTES[0]
}

function hexToRgb(hex) {
  const r = parseInt(hex.slice(1, 3), 16)
  const g = parseInt(hex.slice(3, 5), 16)
  const b = parseInt(hex.slice(5, 7), 16)
  return { r, g, b }
}

function rgbToHex(r, g, b) {
  return '#' + [r, g, b].map(v => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('')
}

function lighten(hex, amount) {
  const { r, g, b } = hexToRgb(hex)
  return rgbToHex(r + amount, g + amount, b + amount)
}

function darken(hex, amount) {
  const { r, g, b } = hexToRgb(hex)
  return rgbToHex(r - amount, g - amount, b - amount)
}

function hexToHsl(hex) {
  if (!/^#[0-9A-Fa-f]{6}$/.test(hex)) return { h: 18, s: 67, l: 59 }
  const r = parseInt(hex.slice(1, 3), 16) / 255
  const g = parseInt(hex.slice(3, 5), 16) / 255
  const b = parseInt(hex.slice(5, 7), 16) / 255
  const max = Math.max(r, g, b), min = Math.min(r, g, b)
  let h = 0, s = 0
  const l = (max + min) / 2
  if (max !== min) {
    const d = max - min
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min)
    switch (max) {
      case r: h = ((g - b) / d + (g < b ? 6 : 0)) / 6; break
      case g: h = ((b - r) / d + 2) / 6; break
      case b: h = ((r - g) / d + 4) / 6; break
    }
  }
  return { h: h * 360, s: s * 100, l: l * 100 }
}

function hslToHex(h, s, l) {
  h = ((h % 360) + 360) % 360
  s = Math.max(0, Math.min(100, s)) / 100
  l = Math.max(0, Math.min(100, l)) / 100
  const c = (1 - Math.abs(2 * l - 1)) * s
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1))
  const m = l - c / 2
  let r = 0, g = 0, b = 0
  if (h < 60)       { r = c; g = x; b = 0 }
  else if (h < 120) { r = x; g = c; b = 0 }
  else if (h < 180) { r = 0; g = c; b = x }
  else if (h < 240) { r = 0; g = x; b = c }
  else if (h < 300) { r = x; g = 0; b = c }
  else              { r = c; g = 0; b = x }
  return '#' + [r + m, g + m, b + m].map(v => Math.round(Math.max(0, Math.min(255, v * 255))).toString(16).padStart(2, '0')).join('')
}

// Génère une palette complète depuis une couleur d'accent et un fond.
export function generatePaletteFromColors(accentHex, bgHex) {
  if (!/^#[0-9A-Fa-f]{6}$/.test(accentHex)) accentHex = '#d97757'
  if (!/^#[0-9A-Fa-f]{6}$/.test(bgHex)) bgHex = '#f5f0ea'

  const { r, g, b } = hexToRgb(accentHex)
  const accentRgb = `${r}, ${g}, ${b}`
  const accentLight = lighten(accentHex, 30)
  const accentDark = darken(accentHex, 35)
  const gradientFrom = darken(accentHex, 70)
  const { h } = hexToHsl(accentHex)

  // Light mode — bg colors derived from bgHex
  const bgCard = '#ffffff'
  const bgSurface = darken(bgHex, 8)
  const border = darken(bgHex, 18)
  const hover = darken(bgHex, 8)
  const textPrimary = hslToHex(h, 40, 12)
  const textMuted = hslToHex(h, 20, 55)
  const shadowRgbVal = hexToRgb(textPrimary)
  const shadowRgb = `${shadowRgbVal.r}, ${shadowRgbVal.g}, ${shadowRgbVal.b}`

  // Dark mode — derived from accent hue
  const bgPageDark = hslToHex(h, 22, 10)
  const bgCardDark = hslToHex(h, 18, 14)
  const bgSurfaceDark = hslToHex(h, 20, 18)
  const textPrimaryDark = hslToHex(h, 30, 92)
  const textMutedDark = hslToHex(h, 18, 58)
  const borderDark = hslToHex(h, 20, 20)
  const hoverDark = hslToHex(h, 18, 16)
  const accentLightRgb = hexToRgb(accentLight)

  return {
    light: {
      accent: accentHex, accentLight, accentDark, accentRgb,
      bgPage: bgHex, bgCard, bgSurface,
      textPrimary, textMuted, border, hover, shadowRgb,
      gradientFrom, gradientMid: accentHex, gradientTo: accentDark,
    },
    dark: {
      accent: accentLight,
      accentLight: lighten(accentHex, 50),
      accentDark: accentHex,
      accentRgb: `${accentLightRgb.r}, ${accentLightRgb.g}, ${accentLightRgb.b}`,
      bgPage: bgPageDark, bgCard: bgCardDark, bgSurface: bgSurfaceDark,
      textPrimary: textPrimaryDark, textMuted: textMutedDark,
      border: borderDark, hover: hoverDark, shadowRgb: '0, 0, 0',
      gradientFrom, gradientMid: accentHex, gradientTo: accentDark,
    },
  }
}

// Génère une palette en calculant automatiquement le fond depuis la teinte de l'accent.
export function generateCustomPalette(accentHex) {
  if (!/^#[0-9A-Fa-f]{6}$/.test(accentHex)) accentHex = '#d97757'
  const { h } = hexToHsl(accentHex)
  const bgHex = hslToHex(h, 40, 96)
  return generatePaletteFromColors(accentHex, bgHex)
}
